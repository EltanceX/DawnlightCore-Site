import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const required = (name) => {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`${name} is required`);
  return value;
};

const digestPattern = /^sha256:[0-9a-f]{64}$/;
const revisionPattern = /^[0-9a-f]{40}$/;
const revision = required("IMAGE_REVISION");
if (!revisionPattern.test(revision)) {
  throw new Error("IMAGE_REVISION must be a full lowercase commit hash");
}

const tag = required("IMAGE_TAG");
if (tag !== `sha-${revision}`) {
  throw new Error("IMAGE_TAG must be derived from the full source revision");
}

const image = (component, repository, digestName, attestationName) => {
  const digest = required(digestName);
  if (!digestPattern.test(digest)) {
    throw new Error(`${digestName} must be a sha256 manifest digest`);
  }
  return {
    component,
    repository,
    tag,
    digest,
    immutableReference: `${repository}@${digest}`,
    attestationUrl: required(attestationName),
    scanReport: `reports/image-scans/${component}.json`,
    sbom: "OCI registry referrer generated by Docker Buildx",
    provenance: "mode=max OCI registry referrer plus GitHub OIDC attestation",
  };
};

const repository = required("GITHUB_REPOSITORY");
const serverUrl = required("GITHUB_SERVER_URL");
const runId = required("GITHUB_RUN_ID");
const manifest = {
  schemaVersion: 1,
  status: "candidate",
  source: {
    repository,
    url: required("IMAGE_SOURCE"),
    revision,
    ref: required("GITHUB_REF"),
    workflow: required("GITHUB_WORKFLOW"),
    runId,
    runAttempt: Number(required("GITHUB_RUN_ATTEMPT")),
    runUrl: `${serverUrl}/${repository}/actions/runs/${runId}`,
  },
  build: {
    created: required("IMAGE_CREATED"),
    sourceDateEpoch: Number(required("SOURCE_DATE_EPOCH")),
    version: required("IMAGE_VERSION"),
    platform: "linux/amd64",
    siteMode: required("SITE_MODE"),
    siteOrigin: required("SITE_ORIGIN"),
    apiOrigin: required("API_ORIGIN"),
  },
  vulnerabilityPolicy: {
    scanner: "Trivy v0.74.0",
    reportedSeverities: ["HIGH", "CRITICAL"],
    maximumAllowedCritical: 0,
  },
  images: [
    image("web", required("WEB_IMAGE"), "WEB_DIGEST", "WEB_ATTESTATION_URL"),
    image("api", required("API_IMAGE"), "API_DIGEST", "API_ATTESTATION_URL"),
    image(
      "worker",
      required("WORKER_IMAGE"),
      "WORKER_DIGEST",
      "WORKER_ATTESTATION_URL",
    ),
  ],
  boundary:
    "Candidate evidence only; deployment approval and Validator supply chain remain separate gates.",
};

const outputPath = resolve("reports/wp9-ci-image-manifest.json");
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Wrote ${outputPath}`);
